"""CareSentry-AI Reflection & Self-Healing Loop.

Implements FR-05:
- On clinical invariant failure, initiates up to 3 automatic re-prompt cycles.
- Applies temperature reduction (Delta T = -0.05) per attempt to increase deterministic adherence.
- Injects formatted reflection feedback identifying the exact medical constraint violated.
"""

from __future__ import annotations

import copy
import logging
from dataclasses import asdict, dataclass
from typing import Any, Callable, Dict, List, Optional

from harness.clinical_linter import (
    audit_clinical_safety,
    load_clinical_rules,
)

logger = logging.getLogger("caresentry.self_healer")


@dataclass
class HealingCycleRecord:
    """Record of a single cycle in the self-healing loop."""
    cycle: int
    temperature: float
    summary: str
    status: str
    violations: List[Dict[str, Any]]
    reflection_prompt_injected: Optional[str] = None


@dataclass
class ReflectionResult:
    """Complete summary of the reflection loop execution."""
    initial_status: str
    final_status: str
    healed: bool
    total_cycles_run: int
    max_cycles: int
    final_temperature: float
    final_summary: str
    cycles: List[HealingCycleRecord]
    remaining_violations: List[Dict[str, Any]]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class SelfHealingLoop:
    """Automated Reflection & Invariant Repair Orchestrator."""

    def __init__(
        self,
        rules: Optional[Dict[str, Any]] = None,
        max_cycles: int = 3,
        initial_temperature: float = 0.70,
        temperature_step: float = -0.05,
    ):
        self.rules = rules or load_clinical_rules()
        self.max_cycles = max_cycles
        self.initial_temperature = initial_temperature
        self.temperature_step = temperature_step

    def format_reflection_prompt(self, violations: List[Dict[str, Any]]) -> str:
        """Construct the standardized clinical reflection feedback prompt."""
        if not violations:
            return ""

        v_descriptions = []
        for v in violations:
            v_type = v.get("type", "SAFETY_VIOLATION")
            offending = v.get("offending_drug", "contraindicated medication")
            rec = v.get("recommendation", "")
            v_descriptions.append(f"[{v_type}] Detected '{offending}'. {rec}")

        details = " ".join(v_descriptions)
        return (
            f"CRITICAL SAFETY VIOLATION: The patient records show clinical contraindications: {details} "
            f"Remove all contraindicated medications immediately and re-verify against patient allergies and renal panel."
        )

    def run(
        self,
        raw_ehr: str,
        initial_summary: str,
        generator_callback: Optional[Callable[[str, str, float], str]] = None,
    ) -> ReflectionResult:
        """Execute the self-healing reflection loop.

        Args:
            raw_ehr: The unadulterated patient medical record / discharge notes.
            initial_summary: The initial draft summary generated by the model.
            generator_callback: Optional callable (prompt, reflection, temperature) -> str
                                If None, applies deterministic clinical substitution heuristic.
        """
        cycles_log: List[HealingCycleRecord] = []
        current_temp = self.initial_temperature
        current_summary = initial_summary

        # Initial validation
        initial_report = audit_clinical_safety(raw_ehr, current_summary, self.rules)
        initial_status = initial_report["status"]

        cycles_log.append(
            HealingCycleRecord(
                cycle=0,
                temperature=current_temp,
                summary=current_summary,
                status=initial_status,
                violations=copy.deepcopy(initial_report["violations"]),
                reflection_prompt_injected=None,
            )
        )

        if initial_status == "PASS":
            return ReflectionResult(
                initial_status="PASS",
                final_status="PASS",
                healed=False,
                total_cycles_run=0,
                max_cycles=self.max_cycles,
                final_temperature=current_temp,
                final_summary=current_summary,
                cycles=cycles_log,
                remaining_violations=[],
            )

        # Invariant failure: begin reflection cycles
        current_violations = initial_report["violations"]
        healed = False

        for cycle in range(1, self.max_cycles + 1):
            current_temp = max(0.0, current_temp + self.temperature_step)
            reflection_prompt = self.format_reflection_prompt(current_violations)

            # Generate corrected summary
            if generator_callback is not None:
                current_summary = generator_callback(raw_ehr, reflection_prompt, current_temp)
            else:
                current_summary = self._deterministic_repair(
                    current_summary, current_violations
                )

            # Re-evaluate
            re_eval = audit_clinical_safety(raw_ehr, current_summary, self.rules)
            current_status = re_eval["status"]
            current_violations = re_eval["violations"]

            cycles_log.append(
                HealingCycleRecord(
                    cycle=cycle,
                    temperature=round(current_temp, 3),
                    summary=current_summary,
                    status=current_status,
                    violations=copy.deepcopy(current_violations),
                    reflection_prompt_injected=reflection_prompt,
                )
            )

            if current_status == "PASS":
                healed = True
                break

        final_status = "PASS" if healed else "WITHHELD"
        if not healed:
            final_summary = (
                "[WITHHELD BY CARESENTRY SAFETY GATE: Unresolved clinical invariant violations persist. "
                "Summary withheld from patient release for clinical safety review.]"
            )
        else:
            final_summary = current_summary

        return ReflectionResult(
            initial_status=initial_status,
            final_status=final_status,
            healed=healed,
            total_cycles_run=len(cycles_log) - 1,
            max_cycles=self.max_cycles,
            final_temperature=round(current_temp, 3),
            final_summary=final_summary,
            cycles=cycles_log,
            remaining_violations=current_violations,
        )

    def _deterministic_repair(
        self,
        summary: str,
        violations: List[Dict[str, Any]],
    ) -> str:
        """Deterministic remediation heuristic replacing offending drugs with safe alternatives."""
        repaired = summary

        # Replacements mapping
        safe_substitutes = {
            "amoxicillin": "Azithromycin 250 mg PO daily",
            "augmentin": "Azithromycin 250 mg PO daily",
            "ampicillin": "Vancomycin IV",
            "penicillin": "Ciprofloxacin 500 mg PO BID",
            "bactrim": "Cephalexin 500 mg PO BID",
            "bactrim ds": "Cephalexin 500 mg PO BID",
            "septra": "Cephalexin 500 mg PO BID",
            "metformin": "Linagliptin 5 mg PO daily (renal dose)",
            "spironolactone": "Furosemide 40 mg PO QAM",
            "ibuprofen": "Acetaminophen 500 mg PO Q8H PRN",
            "naproxen": "Acetaminophen 500 mg PO Q8H PRN",
            "meloxicam": "Acetaminophen 500 mg PO Q8H PRN",
            "ketorolac": "Acetaminophen 500 mg PO Q8H PRN",
            "colchicine": "Prednisone 20 mg PO daily short taper",
            "levofloxacin": "Cefdinir 300 mg PO BID",
        }

        for v in violations:
            offending = v.get("offending_drug", "").lower()
            if not offending:
                continue

            import re
            pattern = re.compile(rf"\b{re.escape(offending)}\b[^\.\n;,]*", re.IGNORECASE)
            substitute = safe_substitutes.get(offending, "safe non-contraindicated therapy")
            repaired = pattern.sub(substitute, repaired)

        return repaired
